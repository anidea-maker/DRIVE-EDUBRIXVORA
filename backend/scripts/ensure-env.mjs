#!/usr/bin/env node
/**
 * Creates or repairs `backend/.env` so Prisma and the API always have the
 * variables they need.
 *
 * Why this exists: Prisma aborts with
 *
 *   Error: Prisma schema validation - (get-config wasm)
 *   Error code: P1012
 *   error: Environment variable not found: DATABASE_URL.
 *
 * whenever no database target is visible to the Prisma CLI, which is what happens
 * on a fresh clone where nobody ran `setup.sh` / `setup.ps1`.
 *
 * Behaviour:
 *   - A Turso target already in the process environment (TURSO_DATABASE_URL +
 *     TURSO_AUTH_TOKEN, or a libsql:// DATABASE_URL) means nothing is written.
 *   - In a container/production runtime with no database at all, this exits
 *     non-zero with the exact variables to set - Prisma would otherwise fail two
 *     steps later with a P1012 that hides the cause.
 *   - Otherwise missing keys are appended to `backend/.env`, creating the file
 *     when it does not exist. Existing values are never overwritten.
 *   - No `DATABASE_URL` and no Turso credentials on a development machine means a
 *     local SQLite file (`file:./prisma/dev.db`), so the app runs without an
 *     account. Nothing is downloaded and no server is needed.
 *   - Secrets are generated with crypto.randomBytes, so a repaired file is usable
 *     immediately.
 *
 * Run it directly with: `npm run env:setup`
 * It also runs automatically before `dev`, `start`, and the Prisma CLI scripts.
 */
import { randomBytes } from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const backendDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const envPath = path.join(backendDir, '.env')

const randomKey = () => randomBytes(32).toString('hex')

/** Ordered list of the keys the backend needs, with a value factory for each. */
const REQUIRED_KEYS = [
  ['DATABASE_URL', () => 'file:./prisma/dev.db'],
  ['APP_PORT', () => '4000'],
  ['FRONTEND_URL', () => 'http://localhost:5173'],
  ['JWT_ACCESS_SECRET', randomKey],
  ['TOKEN_ENCRYPTION_KEY', randomKey],
]

/** Optional keys written only when the file is created from scratch. */
const DEFAULT_KEYS = [
  ['ACCESS_TOKEN_TTL_SECONDS', '900'],
  ['REFRESH_TOKEN_TTL_DAYS', '30'],
  ['MAX_UPLOAD_BYTES', '5368709120'],
  ['GOOGLE_CLIENT_ID', ''],
  ['GOOGLE_CLIENT_SECRET', ''],
  ['GOOGLE_REDIRECT_URI', 'http://localhost:4000/connected-accounts/google/callback'],
]

const HEADER = `# Generated by backend/scripts/ensure-env.mjs.
# Local development configuration - this file is git-ignored.
#
# Turso (production): set both of these instead of DATABASE_URL
#   TURSO_DATABASE_URL="libsql://<database>-<org>.turso.io"
#   TURSO_AUTH_TOKEN="<turso db tokens create <database>>"
# Offline development: DATABASE_URL="file:./prisma/dev.db" (the default below)
`

const serialize = ([key, valueOrFactory]) => {
  const value = typeof valueOrFactory === 'function' ? valueOrFactory() : valueOrFactory
  return `${key}="${value}"`
}

/** Containers and orchestrators inject their own env - never invent a local file there. */
const isManagedRuntime = () =>
  process.env.NODE_ENV === 'production' ||
  fs.existsSync('/.dockerenv') ||
  Boolean(process.env.KUBERNETES_SERVICE_HOST)

/** Reads KEY="value" pairs, ignoring comments. Local copy to keep this file standalone. */
function readEnv(contents) {
  const map = new Map()
  for (const line of contents.split(/\r?\n/)) {
    const match = /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$/.exec(line)
    if (!match || line.trimStart().startsWith('#')) continue
    let value = match[2].trim()
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1)
    }
    map.set(match[1], value)
  }
  return map
}

function main() {
  const shellDatabaseUrl = process.env.DATABASE_URL?.trim()
  const shellTursoUrl = process.env.TURSO_DATABASE_URL?.trim()
  const shellTursoToken = process.env.TURSO_AUTH_TOKEN?.trim()
  const configInShell = Boolean(shellTursoUrl || shellDatabaseUrl)
  const exists = fs.existsSync(envPath)

  if (configInShell) {
    console.log('[env] Database configuration is set in the environment - leaving backend/.env untouched.')
    if (shellTursoUrl && !shellTursoToken) {
      console.warn('[env] TURSO_DATABASE_URL is set without TURSO_AUTH_TOKEN; connections will fail until a token is provided.')
    }
    if (shellDatabaseUrl?.startsWith('mysql://')) {
      console.warn(
        '[env] DATABASE_URL still points at MySQL. This build stores data in SQLite/Turso:\n' +
          '      set TURSO_DATABASE_URL + TURSO_AUTH_TOKEN (see backend/prisma/legacy-mysql/README.md).',
      )
    }
    return
  }

  if (!exists && isManagedRuntime()) {
    // Nothing can rescue this: Prisma would fail two steps later with a P1012 that
    // hides the real cause. Stop here with the variable names and the shape to use.
    console.error(
      [
        '',
        '=== Database is not configured =========================================',
        'No Turso credentials are present in this container\'s environment and',
        'there is no backend/.env to fall back on (containers never create one).',
        '',
        'Set these in the hosting dashboard (Render: service -> Environment):',
        '',
        '  TURSO_DATABASE_URL=libsql://<database>-<org>.turso.io',
        '  TURSO_AUTH_TOKEN=<token>',
        '',
        'Get both from Turso: `turso db show <database> --url` and',
        '`turso db tokens create <database>`, or copy them from the dashboard.',
        'A local development machine can use DATABASE_URL="file:./prisma/dev.db"',
        'instead. Then redeploy - `npm run db:check` verifies the connection.',
        '=======================================================================',
        '',
      ].join('\n'),
    )
    process.exit(1)
  }

  const existingContents = exists ? fs.readFileSync(envPath, 'utf8') : ''
  const existingKeys = readEnv(existingContents)

  // A previous MySQL deployment's DATABASE_URL would block the SQLite default and
  // then fail at startup. Rewrite only that exact leftover, never a real Turso URL.
  let contents = existingContents
  const storedUrl = existingKeys.get('DATABASE_URL')?.trim() ?? ''
  if (/^(mysql|mysqls|mariadb):\/\//i.test(storedUrl)) {
    contents = contents.replace(
      /^(\s*DATABASE_URL\s*=\s*).*$/m,
      '$1"file:./prisma/dev.db"',
    )
    console.warn('[env] Replaced the leftover MySQL DATABASE_URL with a local SQLite file.')
  }

  const known = readEnv(contents)
  const missing = REQUIRED_KEYS.filter(([key]) => !known.get(key)?.trim())

  if (exists && missing.length === 0 && contents === existingContents) return

  if (!exists && contents === '') {
    const lines = [
      HEADER,
      ...REQUIRED_KEYS.map(serialize),
      '',
      ...DEFAULT_KEYS.map(([key, value]) => `${key}="${value}"`),
      '',
    ]
    fs.writeFileSync(envPath, lines.join('\n'), { mode: 0o600 })
    console.log('[env] Created backend/.env with a local SQLite DATABASE_URL and fresh secrets.')
    console.log('[env] Set TURSO_DATABASE_URL + TURSO_AUTH_TOKEN there to use your Turso database.')
    return
  }

  const created = !exists
  if (created) contents = `${HEADER}\n${contents}`

  if (missing.length > 0) {
    const appended = missing.map(serialize)
    const separator = contents === '' || contents.endsWith('\n') ? '' : '\n'
    contents = `${contents}${separator}\n# Added by backend/scripts/ensure-env.mjs\n${appended.join('\n')}\n`
  }

  fs.writeFileSync(envPath, contents, { mode: 0o600 })

  if (created) {
    console.log('[env] Created backend/.env from the environment.')
  }
  if (missing.length > 0) {
    const names = missing.map(([key]) => key).join(', ')
    console.log(`[env] backend/.env was incomplete - added: ${names}.`)
    if (missing.some(([key]) => key === 'DATABASE_URL')) {
      console.log('[env] DATABASE_URL defaults to file:./prisma/dev.db (local SQLite) - edit backend/.env to use Turso.')
    }
    if (missing.some(([key]) => key === 'JWT_ACCESS_SECRET' || key === 'TOKEN_ENCRYPTION_KEY')) {
      console.log('[env] Generated new random values for the missing secret(s).')
    }
  } else if (contents !== existingContents) {
    console.log('[env] Updated backend/.env.')
  }
}

main()
