#!/usr/bin/env node
/**
 * Creates or repairs `backend/.env` so Prisma and the API always have the
 * variables they need.
 *
 * Why this exists: Prisma aborts with
 *
 *   Error: Prisma schema validation - (get-config wasm)
 *   Error code: P1012
 *   error: Environment variable not found: DATABASE_URL.
 *
 * whenever `DATABASE_URL` is not visible to the Prisma CLI, which is what
 * happens on a fresh clone where nobody ran `setup.sh` / `setup.ps1`.
 *
 * Behaviour:
 *   - If DATABASE_URL is already in the process environment (Docker, PM2,
 *     a hosting platform's secret manager, CI), nothing is written.
 *   - Otherwise missing keys are appended to `backend/.env`, creating the file
 *     when it does not exist. Existing values are never overwritten.
 *   - Secrets are generated with crypto.randomBytes, so a repaired file is
 *     usable immediately.
 *
 * Run it directly with: `npm run env:setup`
 * It also runs automatically before `dev`, `start`, and every `prisma:*` script.
 */
import { randomBytes } from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const backendDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const envPath = path.join(backendDir, '.env')

const randomKey = () => randomBytes(32).toString('hex')

/** Ordered list of the keys the backend needs, with a value factory for each. */
const REQUIRED_KEYS = [
  ['DATABASE_URL', () => 'mysql://root@localhost:3306/9drive'],
  ['APP_PORT', () => '4000'],
  ['FRONTEND_URL', () => 'http://localhost:5173'],
  ['JWT_ACCESS_SECRET', randomKey],
  ['TOKEN_ENCRYPTION_KEY', randomKey],
]

/** Optional keys written only when the file is created from scratch. */
const DEFAULT_KEYS = [
  ['ACCESS_TOKEN_TTL_SECONDS', '900'],
  ['REFRESH_TOKEN_TTL_DAYS', '30'],
  ['MAX_UPLOAD_BYTES', '5368709120'],
  ['RECAPTCHA_SECRET_KEY', ''],
  ['GOOGLE_CLIENT_ID', ''],
  ['GOOGLE_CLIENT_SECRET', ''],
  ['GOOGLE_REDIRECT_URI', 'http://localhost:4000/connected-accounts/google/callback'],
]

const HEADER = `# Generated by backend/scripts/ensure-env.mjs.
# Local development configuration - this file is git-ignored.
`

const serialize = ([key, valueOrFactory]) => {
  const value = typeof valueOrFactory === 'function' ? valueOrFactory() : valueOrFactory
  return `${key}="${value}"`
}

/** Minimal .env parser: enough to detect which keys are present. */
function readEnvKeys(contents) {
  const keys = new Map()
  for (const rawLine of contents.split(/\r?\n/)) {
    const line = rawLine.trim()
    if (!line || line.startsWith('#')) continue
    const separator = line.indexOf('=')
    if (separator === -1) continue
    const key = line.slice(0, separator).trim().replace(/^export\s+/, '')
    const value = line
      .slice(separator + 1)
      .trim()
      .replace(/^(['"])(.*)\1$/s, '$2')
    keys.set(key, value)
  }
  return keys
}

/** Containers and orchestrators inject their own env - never invent a localhost DB there. */
const isManagedRuntime = () =>
  process.env.NODE_ENV === 'production' ||
  fs.existsSync('/.dockerenv') ||
  Boolean(process.env.KUBERNETES_SERVICE_HOST)

function main() {
  const shellDatabaseUrl = process.env.DATABASE_URL?.trim()
  if (shellDatabaseUrl) {
    console.log('[env] DATABASE_URL is set in the environment - leaving backend/.env untouched.')
    return
  }

  const exists = fs.existsSync(envPath)

  if (!exists && isManagedRuntime()) {
    console.warn(
      '[env] No backend/.env and no DATABASE_URL in the environment. Containers and ' +
        'production runtimes are expected to inject DATABASE_URL - set it there and retry.',
    )
    return
  }

  const existingContents = exists ? fs.readFileSync(envPath, 'utf8') : ''
  const existingKeys = readEnvKeys(existingContents)

  const missing = REQUIRED_KEYS.filter(([key]) => !existingKeys.get(key)?.trim())

  if (exists && missing.length === 0) return

  if (!exists) {
    const lines = [
      HEADER,
      ...REQUIRED_KEYS.map(serialize),
      '',
      ...DEFAULT_KEYS.map(([key, value]) => `${key}="${value}"`),
      '',
    ]
    fs.writeFileSync(envPath, lines.join('\n'), { mode: 0o600 })
    console.log('[env] Created backend/.env with a local MySQL DATABASE_URL and fresh secrets.')
    console.log('[env] Point DATABASE_URL at your own MySQL server if it is not localhost:3306.')
    return
  }

  const appended = missing.map(serialize)
  const separator = existingContents.endsWith('\n') || existingContents === '' ? '' : '\n'
  fs.writeFileSync(
    envPath,
    `${existingContents}${separator}\n# Added by backend/scripts/ensure-env.mjs\n${appended.join('\n')}\n`,
    { mode: 0o600 },
  )

  const names = missing.map(([key]) => key).join(', ')
  console.log(`[env] backend/.env was incomplete - added: ${names}.`)
  if (missing.some(([key]) => key === 'DATABASE_URL')) {
    console.log('[env] DATABASE_URL defaults to mysql://root@localhost:3306/9drive - edit backend/.env if needed.')
  }
  if (missing.some(([key]) => key === 'JWT_ACCESS_SECRET' || key === 'TOKEN_ENCRYPTION_KEY')) {
    console.log('[env] Generated new random values for the missing secret(s).')
  }
}

main()
