#!/usr/bin/env node
/**
 * Creates or repairs `backend/.env` so Prisma and the API always have the
 * variables they need.
 *
 * Why this exists: Prisma aborts with
 *
 *   Error: Prisma schema validation - (get-config wasm)
 *   Error code: P1012
 *   error: Environment variable not found: DATABASE_URL.
 *
 * whenever `DATABASE_URL` is not visible to the Prisma CLI, which is what
 * happens on a fresh clone where nobody ran `setup.sh` / `setup.ps1`.
 *
 * Behaviour:
 *   - If DATABASE_URL is already in the process environment (Docker, PM2,
 *     a hosting platform's secret manager, CI), nothing is written.
 *   - In a container/production runtime with no DATABASE_URL at all, this exits
 *     non-zero with the exact variable to set - Prisma would otherwise fail two
 *     steps later with a P1012 that hides the cause.
 *   - Otherwise missing keys are appended to `backend/.env`, creating the file
 *     when it does not exist. Existing values are never overwritten.
 *   - Secrets are generated with crypto.randomBytes, so a repaired file is
 *     usable immediately.
 *   - A `DATABASE_CA_CERT` / `DATABASE_SSL_CA` env var (PEM text, base64, or a
 *     file path) is written to `prisma/certs/db-ca.pem` and referenced from the
 *     `DATABASE_URL` stored in `backend/.env`. `prisma-run.mjs` does the same in
 *     the process that actually runs the Prisma CLI.
 *
 * Run it directly with: `npm run env:setup`
 * It also runs automatically before `dev`, `start`, and the Prisma CLI scripts.
 */
import { randomBytes } from 'node:crypto'
import fs from 'node:fs'
import {
  caValueFromEnv,
  envPath,
  normalizePem,
  readEnv,
  setEnvValue,
  withCaCert,
  writeCaFile,
} from './lib/env-config.mjs'

const randomKey = () => randomBytes(32).toString('hex')

/** Ordered list of the keys the backend needs, with a value factory for each. */
const REQUIRED_KEYS = [
  ['DATABASE_URL', () => 'mysql://root@localhost:3306/9drive'],
  ['APP_PORT', () => '4000'],
  ['FRONTEND_URL', () => 'http://localhost:5173'],
  ['JWT_ACCESS_SECRET', randomKey],
  ['TOKEN_ENCRYPTION_KEY', randomKey],
]

/** Optional keys written only when the file is created from scratch. */
const DEFAULT_KEYS = [
  ['ACCESS_TOKEN_TTL_SECONDS', '900'],
  ['REFRESH_TOKEN_TTL_DAYS', '30'],
  ['MAX_UPLOAD_BYTES', '5368709120'],
  ['RECAPTCHA_SECRET_KEY', ''],
  ['GOOGLE_CLIENT_ID', ''],
  ['GOOGLE_CLIENT_SECRET', ''],
  ['GOOGLE_REDIRECT_URI', 'http://localhost:4000/connected-accounts/google/callback'],
]

const HEADER = `# Generated by backend/scripts/ensure-env.mjs.
# Local development configuration - this file is git-ignored.
`

const serialize = ([key, valueOrFactory]) => {
  const value = typeof valueOrFactory === 'function' ? valueOrFactory() : valueOrFactory
  return `${key}="${value}"`
}

/** Containers and orchestrators inject their own env - never invent a localhost DB there. */
const isManagedRuntime = () =>
  process.env.NODE_ENV === 'production' ||
  fs.existsSync('/.dockerenv') ||
  Boolean(process.env.KUBERNETES_SERVICE_HOST)

/**
 * Materializes the CA certificate when it arrives as an env var and points the
 * `DATABASE_URL` stored in .env at it. Returns the (possibly updated) contents.
 */
function syncCaCertificate(contents, databaseUrlFromEnv) {
  const caValue = caValueFromEnv()
  if (!caValue) return contents

  const pem = normalizePem(caValue)
  if (!pem) {
    console.warn(`[env] ${caValue ? 'DATABASE_CA_CERT is set but contains no "BEGIN CERTIFICATE" block - ignoring it.' : ''}`)
    return contents
  }

  if (!writeCaFile(pem)) return contents
  console.log('[env] Saved the database CA certificate to prisma/certs/db-ca.pem')

  const current = readEnv(contents).get('DATABASE_URL') ?? databaseUrlFromEnv ?? ''
  if (!current.startsWith('mysql://')) return contents

  const patched = withCaCert(current)
  if (databaseUrlFromEnv) {
    console.warn(
      '[env] DATABASE_URL also comes from the process environment, which overrides backend/.env.\n' +
        '      The Prisma CLI uses `npm run prisma:…` (scripts/prisma-run.mjs), which adds the\n' +
        '      TLS parameters to the injected URL automatically:\n' +
        `      ${patched}`,
    )
  } else if (patched !== current) {
    console.log('[env] DATABASE_URL set to use sslcert=certs/db-ca.pem&sslaccept=strict')
  }

  return setEnvValue(contents, 'DATABASE_URL', patched)
}

function main() {
  const shellDatabaseUrl = process.env.DATABASE_URL?.trim()
  const caValue = caValueFromEnv()
  const exists = fs.existsSync(envPath)

  if (shellDatabaseUrl && !caValue) {
    console.log('[env] DATABASE_URL is set in the environment - leaving backend/.env untouched.')
    return
  }

  if (!shellDatabaseUrl && !exists && isManagedRuntime()) {
    // Nothing can rescue this: Prisma would fail two steps later with a P1012 that
    // hides the real cause. Stop here with the variable names and the shape to use.
    console.error(
      [
        '',
        '=== Database is not configured =========================================',
        'No DATABASE_URL is present in this container\'s environment and there is',
        'no backend/.env to fall back on (containers never create one).',
        '',
        'Set it in the hosting dashboard (Render: service -> Environment):',
        '',
        '  DATABASE_URL=mysql://avnadmin:PASSWORD@HOST:PORT/defaultdb',
        '',
        'Managed MySQL (Aiven, PlanetScale, RDS) also needs the provider CA so the',
        'connection is encrypted. Either put it in the URL,',
        '',
        '  DATABASE_URL=mysql://.../defaultdb?sslcert=certs/db-ca.pem&sslaccept=strict',
        '',
        'or paste the ca.pem contents (PEM or base64) into DATABASE_CA_CERT and the',
        'app writes prisma/certs/db-ca.pem and adds those parameters automatically.',
        '',
        'Then redeploy. `npm run db:check` verifies host, TLS and credentials.',
        '=======================================================================',
        '',
      ].join('\n'),
    )
    process.exit(1)
  }

  const existingContents = exists ? fs.readFileSync(envPath, 'utf8') : ''
  const withTls = syncCaCertificate(existingContents, shellDatabaseUrl)
  const existingKeys = readEnv(withTls)
  const missing = REQUIRED_KEYS.filter(([key]) => !existingKeys.get(key)?.trim())

  if (exists && missing.length === 0 && withTls === existingContents) return

  if (!exists && withTls === '') {
    const lines = [
      HEADER,
      ...REQUIRED_KEYS.map(serialize),
      '',
      ...DEFAULT_KEYS.map(([key, value]) => `${key}="${value}"`),
      '',
    ]
    fs.writeFileSync(envPath, lines.join('\n'), { mode: 0o600 })
    console.log('[env] Created backend/.env with a local MySQL DATABASE_URL and fresh secrets.')
    console.log('[env] Point DATABASE_URL at your own MySQL server if it is not localhost:3306.')
    return
  }

  let contents = withTls
  let created = false

  if (!exists) {
    contents = `${HEADER}\n${withTls}`
    created = true
  }

  if (missing.length > 0) {
    const appended = missing.map(serialize)
    const separator = contents === '' || contents.endsWith('\n') ? '' : '\n'
    contents = `${contents}${separator}\n# Added by backend/scripts/ensure-env.mjs\n${appended.join('\n')}\n`
  }

  fs.writeFileSync(envPath, contents, { mode: 0o600 })

  if (created) {
    console.log('[env] Created backend/.env from the environment (DATABASE_URL included).')
  }
  if (missing.length > 0) {
    const names = missing.map(([key]) => key).join(', ')
    console.log(`[env] backend/.env was incomplete - added: ${names}.`)
    if (missing.some(([key]) => key === 'DATABASE_URL')) {
      console.log('[env] DATABASE_URL defaults to mysql://root@localhost:3306/9drive - edit backend/.env if needed.')
    }
    if (missing.some(([key]) => key === 'JWT_ACCESS_SECRET' || key === 'TOKEN_ENCRYPTION_KEY')) {
      console.log('[env] Generated new random values for the missing secret(s).')
    }
  } else if (contents !== existingContents) {
    console.log('[env] Updated backend/.env.')
  }
}

main()
